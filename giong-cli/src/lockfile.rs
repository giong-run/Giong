//! Cargo.lock, read without a TOML crate: the packages, their versions,
//! where they come from and what they depend on (lock versions 1 to 4).

use crate::host::{self, Version};

/// Where a locked package comes from.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Source {
    /// A registry: crates.io, or a mirror that replaces it.
    Registry,
    /// A git repository.
    Git,
    /// A path: a member of the workspace or a checkout (`path = "..."`).
    Path,
}

/// One `[[package]]` of a Cargo.lock.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Locked {
    pub name: String,
    pub version: Version,
    pub source: Source,
    /// The names of the packages it depends on.
    pub deps: Vec<String>,
    /// The line of its `name = ...` (1-based).
    pub line: u32,
}

/// A `[[package]]` while it is read.
#[derive(Default)]
struct Partial {
    name: String,
    version: Option<Version>,
    source: Option<Source>,
    deps: Vec<String>,
    line: u32,
}

impl Partial {
    fn done(self) -> Option<Locked> {
        Some(Locked {
            name: self.name,
            version: self.version?,
            source: self.source.unwrap_or(Source::Path),
            deps: self.deps,
            line: self.line,
        })
    }
}

/// Every package of a Cargo.lock (versions 1 to 4).
pub fn parse_lock(text: &str) -> Vec<Locked> {
    let mut out = Vec::new();
    let mut cur: Option<Partial> = None;
    let mut in_deps = false;
    let dep_name = |item: &str| -> Option<String> {
        // `"giong 1.5.0",` or `"giong 1.5.0 (registry+...)",` or `"giong",`
        let item = item.trim().trim_end_matches(',').trim_matches('"');
        item.split_whitespace().next().map(String::from)
    };
    for (i, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.starts_with('[') {
            in_deps = false;
            out.extend(cur.take().and_then(Partial::done));
            if line == "[[package]]" {
                cur = Some(Partial::default());
            }
            continue;
        }
        let Some(c) = cur.as_mut() else { continue };
        if in_deps {
            if line.starts_with(']') {
                in_deps = false;
            } else {
                c.deps.extend(dep_name(line));
            }
            continue;
        }
        if let Some(v) = line.strip_prefix("name = ") {
            c.name = v.trim_matches('"').to_string();
            c.line = i as u32 + 1;
        } else if let Some(v) = line.strip_prefix("version = ") {
            c.version = host::parse_version(v.trim_matches('"'));
        } else if let Some(v) = line.strip_prefix("source = ") {
            c.source = Some(if v.trim_matches('"').starts_with("git+") {
                Source::Git
            } else {
                Source::Registry
            });
        } else if let Some(rest) = line.strip_prefix("dependencies = [") {
            match rest.trim().strip_suffix(']') {
                // Cargo.lock version 1 wrote short lists on one line.
                Some(inline) => c.deps.extend(inline.split(',').filter_map(dep_name)),
                None => in_deps = true,
            }
        }
    }
    out.extend(cur.take().and_then(Partial::done));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn v(s: &str) -> Version {
        host::parse_version(s).unwrap()
    }

    #[test]
    fn the_lock_file_is_read_with_sources_and_dependencies() {
        let lock = "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
                    [[package]]\nname = \"giong\"\nversion = \"1.5.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"ab\"\ndependencies = [\n \"libc\",\n \"socket2 0.6.1\",\n]\n\n\
                    [[package]]\nname = \"giong-web\"\nversion = \"1.4.2\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\ndependencies = [\n \"giong\",\n]\n\n\
                    [[package]]\nname = \"giong-http\"\nversion = \"1.5.0\"\nsource = \"git+https://github.com/giong-run/Giong#abc\"\n\n\
                    [[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\"giong\", \"giong-web\"]\n";
        let all = parse_lock(lock);
        assert_eq!(all.len(), 4, "{all:?}");
        assert_eq!(all[0].name, "giong");
        assert_eq!(all[0].deps, ["libc", "socket2"]);
        assert_eq!(all[0].line, 5);
        assert_eq!(all[1].version, v("1.4.2"));
        assert_eq!(all[1].deps, ["giong"]);
        assert_eq!(all[2].source, Source::Git);
        assert_eq!(all[3].source, Source::Path);
        assert_eq!(all[3].deps, ["giong", "giong-web"]);
    }
}
